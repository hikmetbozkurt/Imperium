    /**
     * Get a specified number of random questions from all ancient questions
     * Used as a fallback when specific level questions aren't available
     */
    fun getRandomQuestions(count: Int): List<Question> {
        val allQuestions = listOf(
            ancientEgyptQuestions,
            egyptianSocietyQuestions,
            egyptianCultureQuestions,
            egyptianLegacyQuestions,
            ancientGreeceQuestions,
            classicalGreeceQuestions,
            greekCultureQuestions,
            ancientRomeQuestions,
            romanRepublicQuestions,
            romanEmpireQuestions,
            mesopotamiaQuestions,
            babylonQuestions,
            ancientChinaQuestions,
            chineseCultureQuestions,
            ancientIndiaQuestions,
            persiaQuestions,
            americasQuestions,
            africaQuestions,
            ancientTechQuestions,
            legacyQuestions
        ).flatten()
        
        return if (allQuestions.isEmpty()) {
            // If there are no questions at all, return empty list
            emptyList()
        } else if (allQuestions.size <= count) {
            // If we don't have enough questions, return all available
            allQuestions
        } else {
            // Return random selection of questions
            allQuestions.shuffled().take(count)
        }
    }
